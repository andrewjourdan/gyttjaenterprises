const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const fields = {acres:40,depth:2,cost:16,credit:6,rev:700,yield:15,fert:180,cut:10};
const elements = {};
const listeners = {};
const get = id => elements[id] ??= {value: fields[id] ?? '', textContent:'', addEventListener(event, fn){listeners[id+':'+event]=fn;}};
const window = {location:{href:''}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../site.js'),'utf8'), {document:{getElementById:get},window,Date,Math,Number,encodeURIComponent,isFinite});
assert.equal(get('total').textContent, '$107,556');
assert.equal(get('annual').textContent, '$123');
assert.equal(get('payback').textContent, '21.9 yrs');
get('yield').value = 0; get('cut').value = 0;
listeners['yield:input']();
assert.equal(get('payback').textContent, 'No payback');
get('yield').value = 15; get('credit').value = 20;
listeners['credit:input']();
assert.equal(get('total').textContent, '$0');
assert.equal(get('payback').textContent, 'Immediate');
get('name').value = 'Example & Visitor';
get('prod').value = 'Compost Blend';
get('msg').value = 'Question? Café & soil';
let prevented = false;
listeners['contactForm:submit']({preventDefault(){prevented=true;}});
assert.ok(prevented);
assert.ok(window.location.href.startsWith('mailto:inquiry@gyttjaenterprises.com?'));
const query = new URLSearchParams(window.location.href.split('?')[1]);
assert.equal(query.get('subject'), 'Gyttja quote request: Compost Blend');
assert.ok(query.get('body').includes('Question? Café & soil'));
console.log('Calculator and email-draft behavior passed; no email sent.');
